def load_cached():
    if not CHUNKS_PARQUET.exists() or not EMBEDDINGS_NPY.exists():
        raise SystemExit(
            "Missing cached artifacts. Run first:\n"
            "  python scripts/build_visuals.py --cache"
        )
    df = pd.read_parquet(CHUNKS_PARQUET).reset_index(drop=True)
    X = np.load(EMBEDDINGS_NPY).astype(np.float32)
    if len(df) != len(X):
        raise SystemExit(
            f"chunks.parquet has {len(df)} rows but embeddings.npy has "
            f"{len(X)}; regenerate both from build_visuals.py --cache"
        )
    return df, X


def digit_density(text: str) -> float:
    if not text:
        return 0.0
    return len(_DIGIT_RE.findall(text)) / max(1, len(text))


def compute_prose_axis(X: np.ndarray, dd: np.ndarray) -> np.ndarray:
    is_table = dd > TABLE_DIGIT_THRESHOLD
    if is_table.sum() < 5 or (~is_table).sum() < 5:
        return PCA(n_components=1, random_state=0).fit(X).components_[0]
    v = X[is_table].mean(0) - X[~is_table].mean(0)
    return v / max(1e-12, np.linalg.norm(v))


def compute_doc_centroids(df: pd.DataFrame, X: np.ndarray):
    """One centroid per (company, doc) pair.  Returns (C, cmeta, ci)."""
    keys = list(zip(df["company"], df["doc"]))
    order: dict = {}
    for k in keys:
        if k not in order:
            order[k] = len(order)
    ci = np.fromiter((order[k] for k in keys), dtype=np.int64, count=len(keys))
    C = np.zeros((len(order), X.shape[1]), dtype=X.dtype)
    counts = np.zeros(len(order), dtype=np.int64)
    for j, c in enumerate(ci):
        C[c] += X[j]
        counts[c] += 1
    C = C / counts[:, None]
    cmeta = [
        {"company": k[0], "doc": k[1], "n_chunks": int(counts[v])}
        for k, v in order.items()
    ]
    return C, cmeta, ci


def compute_company_centroids(df: pd.DataFrame, X: np.ndarray):
    """One centroid per company.  Returns (Cco, cometa, coi) where coi[j]
    is the row of Cco that chunk j belongs to."""
    companies = df["company"].tolist()
    order: dict = {}
    for c in companies:
        if c not in order:
            order[c] = len(order)
    coi = np.fromiter((order[c] for c in companies),
                      dtype=np.int64, count=len(companies))
    Cco = np.zeros((len(order), X.shape[1]), dtype=X.dtype)
    counts = np.zeros(len(order), dtype=np.int64)
    for j, c in enumerate(coi):
        Cco[c] += X[j]
        counts[c] += 1
    Cco = Cco / counts[:, None]
    cometa = [{"company": k, "n_chunks": int(counts[v])} for k, v in order.items()]
    return Cco, cometa, coi


def content_type_of(dd_val: float) -> str:
    """Three-way label used by the content-type filter."""
    if dd_val >= TABLE_DIGIT_THRESHOLD:
        return "tabular"
    if dd_val <= 0.05:
        return "prose"
    return "ambiguous"


def top_neighbors(X: np.ndarray, k: int) -> np.ndarray:
    """Return (N, k) int32 array of top-k neighbor row indices (excluding self)
    computed by cosine similarity on unit-norm vectors."""
    N = len(X)
    out = np.zeros((N, k), dtype=np.int32)
    # process in blocks to keep memory bounded
    block = 512
    for start in range(0, N, block):
        end = min(N, start + block)
        S = X[start:end] @ X.T          # (b, N)
        # exclude self
        for r in range(end - start):
            S[r, start + r] = -np.inf
        idx = np.argpartition(-S, kth=k, axis=1)[:, :k]
        # sort the top-k for a stable UI
        rows = np.arange(end - start)[:, None]
        sorted_order = np.argsort(-S[rows, idx], axis=1)
        idx = idx[rows, sorted_order]
        out[start:end] = idx
        print(f"  neighbors {end}/{N}")
    return out


# --------------------------------------------- alternate projections cache
#
# The main viewer also lets the user swap the PCA embedding for a t-SNE
# or a UMAP embedding of the *same* 384-D corpus. Computing 8 such
# projections (t-SNE at 4 perplexities + UMAP at 4 neighbourhood sizes,
# both in 3D and 2D flavours) is expensive \u2014 roughly two minutes
# total \u2014 so we cache the results on disk, keyed by a SHA hash of
# the embeddings. If the hash matches, we reuse the cache verbatim; if
# it does not, we recompute and overwrite. This keeps the second and
# third `python build_semantic_universe_explorer.py` calls fast.

_PROJECTIONS_CACHE = ROOT / "assets" / "projections_cache.npz"
_TSNE_PERPLEXITIES = [5, 30, 100, 300]
_UMAP_N_NEIGHBORS = [5, 15, 50, 200]
_UMAP_MIN_DIST = 0.1


def _proj_key_tsne(p: int, dim: int) -> str:
    return f"tsne_p{p}_d{dim}"


def _proj_key_umap(n: int, dim: int) -> str:
    return f"umap_n{n}_d{dim}"


def _embedding_hash(X: np.ndarray) -> str:
    """Stable hash of the corpus embeddings; cache key for the projections."""
    import hashlib
    h = hashlib.sha256()
    h.update(str(X.shape).encode())
    # subsample deterministically to keep hashing fast even for large corpora
    step = max(1, X.shape[0] // 256)
    h.update(X[::step].tobytes())
    return h.hexdigest()[:16]


def compute_alt_projections(X: np.ndarray, force: bool = False) -> dict:
    """Compute (and cache) 3D + 2D t-SNE and UMAP embeddings of the corpus.

    Returns a dict keyed by projection name (e.g. "tsne_p30_d3"), value
    being an (N, 3) or (N, 2) float32 array. Falls back gracefully:
    if umap-learn is not installed, UMAP entries are simply omitted.
    """
    from sklearn.manifold import TSNE

    want_key = _embedding_hash(X)
    keys_needed = []
    for p in _TSNE_PERPLEXITIES:
        keys_needed += [_proj_key_tsne(p, 3), _proj_key_tsne(p, 2)]
    for n in _UMAP_N_NEIGHBORS:
        keys_needed += [_proj_key_umap(n, 3), _proj_key_umap(n, 2)]

    if not force and _PROJECTIONS_CACHE.exists():
        try:
            cache = np.load(_PROJECTIONS_CACHE, allow_pickle=False)
            if str(cache.get("_hash", "")) == want_key and all(k in cache for k in keys_needed):
                out = {k: cache[k].astype(np.float32) for k in keys_needed}
                print(f"  loaded alt projections from cache ({len(out)} arrays)")
                return out
            else:
                print("  cache stale, recomputing alt projections")
        except Exception as e:
            print(f"  cache read failed ({e!r}), recomputing alt projections")

    out: dict = {}
    # sklearn renamed n_iter -> max_iter around 1.5. Pick whichever the
    # installed version accepts.
    import inspect
    _tsne_params = set(inspect.signature(TSNE.__init__).parameters)
    _iter_kw = "max_iter" if "max_iter" in _tsne_params else "n_iter"
    for p in _TSNE_PERPLEXITIES:
        for d in (3, 2):
            print(f"  t-SNE perplexity={p} d={d} ...")
            kwargs = dict(
                n_components=d, perplexity=float(p), init="pca",
                random_state=0, learning_rate="auto",
            )
            kwargs[_iter_kw] = 750 if p >= 100 else 1000
            t = TSNE(**kwargs).fit_transform(X)
            out[_proj_key_tsne(p, d)] = t.astype(np.float32)

    try:
        import umap
        for n in _UMAP_N_NEIGHBORS:
            for d in (3, 2):
                print(f"  UMAP n_neighbors={n} d={d} ...")
                u = umap.UMAP(
                    n_neighbors=int(n), min_dist=_UMAP_MIN_DIST,
                    n_components=d, random_state=0, verbose=False,
                ).fit_transform(X)
                out[_proj_key_umap(n, d)] = u.astype(np.float32)
    except ImportError:
        print("  ! umap-learn not installed; skipping UMAP projections")

    try:
        _PROJECTIONS_CACHE.parent.mkdir(parents=True, exist_ok=True)
        np.savez(_PROJECTIONS_CACHE, _hash=np.array(want_key), **out)
        print(f"  cached alt projections \\u2192 {_PROJECTIONS_CACHE}")
    except Exception as e:
        print(f"  ! could not save projections cache: {e}")

    return out


def _center_and_scale(Z: np.ndarray) -> tuple[np.ndarray, float]:
    """Center a projection at 0 and scale it so its 98th-percentile
    absolute coordinate lands near 0.6 \u2014 matches the range PCA
    typically produces, so the camera / axis ranges look consistent
    when the user swaps projections.

    Returns (Z_centered_scaled, r) where r is the half-range used for
    axis ranges (a bit above the 98th pct so a few outliers don't get
    clipped)."""
    Z = np.asarray(Z, dtype=np.float32)
    Z = Z - Z.mean(axis=0, keepdims=True)
    scale = float(np.percentile(np.abs(Z), 98))
    if scale < 1e-9:
        scale = 1.0
    Z = (Z * (0.6 / scale)).astype(np.float32)
    r = float(np.percentile(np.abs(Z), 99)) * 1.05
    if r < 1e-6:
        r = 0.6
    return Z, r


def gmm_cluster_labels(X: np.ndarray, subspace_dims: int = 20) -> np.ndarray:
    p = PCA(n_components=subspace_dims, random_state=0).fit_transform(X)
    gm = GaussianMixture(n_components=2, covariance_type="full",
                         random_state=0).fit(p)
    return gm.predict(p).astype(np.int32)


