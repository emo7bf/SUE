    content_type_of = classify_content_types(df, X)
    _ct_counts = np.bincount(content_type_of.astype(np.int64), minlength=12)
    for k, name in enumerate(_CT_TITLES):
        print(f"    {k:2d} {name:<26} {int(_ct_counts[k]):>5d} chunks")

